/**
 * Inline the startup logo into index.html as a data URI.
 *
 * #app-boot-loader is what covers the wait after a notification tap — the WebView
 * points at the remote site (capacitor.config.ts server.url), so a tap that reaches a
 * backgrounded app repaints from the network. The loader paints with the first byte of
 * HTML, but its logo was `<img src="/college-logo.png">`: a *second* request for a
 * 2000x2000, 356 KB file. On mobile data that arrives long after the markup, so for the
 * whole window the user is complaining about, the startup screen is a bare white page
 * with a spinner — the logo turns up about when the app itself does.
 *
 * A data URI has no request to make: the logo is decoded from the same bytes that
 * brought the markup, so the startup screen looks the same at 100 ms as it does at
 * 5 s. The mark is downscaled to BOOT_LOGO_SIZE first — the loader never renders it
 * larger than 7rem, so the full-resolution file was ~40x more pixels than any screen
 * could use — and keeps its transparency, because here it sits on white.
 *
 * Run: node scripts/generate-boot-logo.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { contentBounds, decodePng, encodePng, renderTile } from "./lib/png.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "..");
const SOURCE = path.join(frontend, "public/college-logo.png");
const INDEX = path.join(frontend, "index.html");

/**
 * 256px covers the loader's largest rendering (7rem = 112px) at 2x, and the phones
 * that need this fix most are the ones where every inlined kilobyte is also latency.
 */
const BOOT_LOGO_SIZE = 256;
const START = "<!-- boot-logo:start (generated by scripts/generate-boot-logo.mjs) -->";
const END = "<!-- boot-logo:end -->";

const source = decodePng(SOURCE);
const crop = contentBounds(source);
const logo = renderTile(source, crop, BOOT_LOGO_SIZE, 1, null);
const png = encodePng(logo, { alpha: true });
const dataUri = `data:image/png;base64,${png.toString("base64")}`;

const html = fs.readFileSync(INDEX, "utf8");
const start = html.indexOf(START);
const end = html.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  throw new Error(`index.html is missing the ${START} / ${END} markers`);
}

const block = `${START}\n      <img src="${dataUri}" alt="PHIT COLLEGE" decoding="sync" />\n      ${END}`;
fs.writeFileSync(INDEX, html.slice(0, start) + block + html.slice(end + END.length));

const sourceBytes = fs.statSync(SOURCE).size;
console.log(
  `inlined ${BOOT_LOGO_SIZE}x${BOOT_LOGO_SIZE} boot logo into index.html - ` +
    `${(png.length / 1024).toFixed(1)} KB png, ${(dataUri.length / 1024).toFixed(1)} KB base64 ` +
    `(was a ${(sourceBytes / 1024).toFixed(0)} KB second request)`,
);
